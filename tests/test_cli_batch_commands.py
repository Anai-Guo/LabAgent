"""In-process tests for the export / campaign / serve / start CLI handlers."""

from __future__ import annotations

import argparse
import json
import sys
import types

import pytest

from lab_harness import cli


def _export_args(data_file, fmt=None, name=None):
    return argparse.Namespace(data_file=str(data_file), format=fmt, name=name)


def _campaign_args(sweep=None, fixed=None, preview=False, measurement_type="IV"):
    return argparse.Namespace(measurement_type=measurement_type, sweep=sweep, fixed=fixed, preview=preview)


def test_cmd_export_missing_file_exits(tmp_path, capsys):
    with pytest.raises(SystemExit) as exc:
        cli.cmd_export(_export_args(tmp_path / "nope.csv"), None)
    assert exc.value.code == 1
    assert "data file not found" in capsys.readouterr().out


@pytest.mark.parametrize(
    "content, message",
    [("# only a comment\n", "data file is empty"), ("field,voltage\n", "no data rows found")],
    ids=["comments-only", "header-only"],
)
def test_cmd_export_rejects_files_without_rows(tmp_path, capsys, content, message):
    src = tmp_path / "data.csv"
    src.write_text(content, encoding="utf-8")
    with pytest.raises(SystemExit) as exc:
        cli.cmd_export(_export_args(src), None)
    assert exc.value.code == 1
    assert message in capsys.readouterr().out


def test_cmd_export_converts_numbers_and_honours_format_and_name(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    src = tmp_path / "sweep.csv"
    src.write_text("# generated by harness\nfield,voltage,label\n0.1,1.5,a\n0.2,x,b\n", encoding="utf-8")
    exports = tmp_path / "data" / "exports"

    cli.cmd_export(_export_args(src, fmt="json", name="run1"), None)
    assert "Exported 2 rows to" in capsys.readouterr().out
    (exported,) = exports.glob("*_run1.json")
    payload = json.loads(exported.read_text(encoding="utf-8"))
    rows = payload["data"] if isinstance(payload, dict) else payload
    assert rows[0]["field"] == 0.1 and rows[0]["voltage"] == 1.5
    assert rows[1]["voltage"] == "x" and rows[1]["label"] == "b"

    cli.cmd_export(_export_args(src), None)  # defaults: csv + input stem
    assert "Exported 2 rows to" in capsys.readouterr().out
    assert len(list(exports.glob("*_sweep.csv"))) == 1


@pytest.mark.parametrize(
    "args, message",
    [
        (_campaign_args(sweep=["field"]), "--sweep must be"),
        (_campaign_args(sweep=[]), "at least one --sweep"),
        (_campaign_args(sweep=["field=1,2"], fixed=["temp"]), "--fixed must be"),
    ],
    ids=["bad-sweep", "no-sweep", "bad-fixed"],
)
def test_cmd_campaign_rejects_malformed_arguments(capsys, args, message):
    with pytest.raises(SystemExit) as exc:
        cli.cmd_campaign(args, None)
    assert exc.value.code == 1
    assert message in capsys.readouterr().out


def test_cmd_campaign_preview_parses_values_without_saving(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    sweep, fixed = ["field=0.1, 0.2,0.3", "mode=up,down"], ["temp=300", "sample=Pt"]

    cli.cmd_campaign(_campaign_args(sweep=sweep, fixed=fixed, preview=True), None)

    out = capsys.readouterr().out
    assert "Campaign preview: IV" in out and "Total points: 6" in out
    assert "field: 3 values (0.1 ... 0.3)" in out
    assert "temp: 300.0" in out and "sample: Pt" in out
    assert not (tmp_path / "data").exists()


def test_cmd_campaign_creates_and_saves_campaign(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    args = _campaign_args(sweep=["field=1,2", "angle=0,90"], fixed=["temp=300"], measurement_type="AHE")

    cli.cmd_campaign(args, None)

    assert "4 points" in capsys.readouterr().out
    (saved,) = (tmp_path / "data" / "campaigns").glob("campaign-*.json")
    data = json.loads(saved.read_text(encoding="utf-8"))
    assert data["measurement_type"] == "AHE"
    assert data["sweep_parameters"] == {"field": [1.0, 2.0], "angle": [0.0, 90.0]}
    assert data["fixed_parameters"] == {"temp": 300.0}
    assert len(data["points"]) == 4


def test_cmd_serve_runs_mcp_server(monkeypatch):
    calls = []
    fake = types.ModuleType("lab_harness.server")
    fake.run_server = lambda: calls.append("served")
    monkeypatch.setitem(sys.modules, "lab_harness.server", fake)
    cli.cmd_serve(argparse.Namespace(), None)
    assert calls == ["served"]


class _FakeFlow:
    instances: list[_FakeFlow] = []
    raise_interrupt = False

    def __init__(self, settings, data_root=None):
        self.settings, self.data_root, self.calls = settings, data_root, []
        _FakeFlow.instances.append(self)

    async def run(self, direction="", material=""):
        self.calls.append((direction, material))
        if _FakeFlow.raise_interrupt:
            raise KeyboardInterrupt


def test_cmd_start_forwards_arguments_and_handles_interrupt(monkeypatch, tmp_path, capsys):
    monkeypatch.setattr("lab_harness.orchestrator.flow.ExperimentFlow", _FakeFlow)

    cli.cmd_start(argparse.Namespace(direction="AHE", material="Pt", data_root=str(tmp_path)), "settings")
    (flow,) = _FakeFlow.instances
    assert flow.settings == "settings" and flow.data_root == tmp_path
    assert flow.calls == [("AHE", "Pt")]

    _FakeFlow.instances, _FakeFlow.raise_interrupt = [], True
    cli.cmd_start(argparse.Namespace(direction=None, material=None, data_root=None), None)
    (flow,) = _FakeFlow.instances
    assert str(flow.data_root) == "data" and flow.calls == [("", "")]
    assert "Cancelled." in capsys.readouterr().out
